export const translations = { en, te, hi }

// Translate a key for the active language, with English fallback and {param} interpolation.
export function translate(language, key, params) {
  const table = translations[language] || translations[DEFAULT_LANGUAGE]
  const fallback = translations[DEFAULT_LANGUAGE]
  let value = table[key] ?? fallback[key] ?? key
  if (params && typeof value === 'string') {
    Object.keys(params).forEach((name) => {
      value = value.split(`{${name}}`).join(String(params[name]))
    })
  }
  return value
}

// Maps internal attribute keys to display-label keys. Used only for display.
const ATTRIBUTE_KEYS = {
  category: 'common.category',
  subcategory: 'common.subcategory',
  gender: 'common.gender',
  color: 'common.color',
  brand: 'common.brand',
  material: 'common.material',
  closure: 'common.closure',
  sole: 'common.sole',
  description: 'productDetails.description',
  keywords: 'common.keywords',
}

// Localized display label for an internal status value (value itself stays unchanged).
export function statusLabel(language, value) {
  const key = `status.${String(value ?? '').toUpperCase()}`
  return translations[DEFAULT_LANGUAGE][key] ? translate(language, key) : String(value ?? '')
}

// Localized display label for a known category value (value itself stays unchanged).
export function categoryLabel(language, value) {
  const key = `category.${value}`
  return translations[DEFAULT_LANGUAGE][key] ? translate(language, key) : String(value ?? '')
}

// Localized display label for an internal attribute/field key.
export function attributeLabel(language, key) {
  const translationKey = ATTRIBUTE_KEYS[key]
  if (translationKey) return translate(language, translationKey)
  return String(key ?? '').replace(/_/g, ' ')
}
